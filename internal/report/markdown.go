package report

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/mrtoadie/go-clustercheck/internal/audit"
)

// mdStatus maps a status to a markdown-friendly marker.
func mdStatus(s audit.Status) string {
	switch s {
	case audit.StatusOK:
		return "✅"
	case audit.StatusWarn:
		return "⚠️"
	case audit.StatusFail:
		return "❌"
	default:
		return "ℹ️"
	}
}

// RenderMarkdown writes the same Result data as a markdown report -
// directly consumable by Obsidian, GitHub or your static site.
func RenderMarkdown(results []audit.Result, version string) {
	w := os.Stdout

	fmt.Fprintf(w, "# Cluster Check Report\n\n")
	fmt.Fprintf(w, "**go-clustercheck** v%s · %s\n\n", version, time.Now().Format("2006-01-02 15:04"))

	fail, warn, ok := 0, 0, 0
	for _, res := range results {
		switch res.Status {
		case audit.StatusFail:
			fail++
		case audit.StatusWarn:
			warn++
		case audit.StatusOK:
			ok++
		}
	}
	fmt.Fprintf(w, "**Summary:** %d checks · ✅ %d ok · ⚠️ %d warnings · ❌ %d failed\n\n",
		len(results), ok, warn, fail)

	fmt.Fprintf(w, "---\n\n")

	for _, res := range results {
		fmt.Fprintf(w, "## %s %s\n\n", mdStatus(res.Status), res.Title)

		if res.Err != nil {
			fmt.Fprintf(w, "> ❌ check failed: %s\n\n", res.Err)
			continue
		}

		fmt.Fprintf(w, "| Status | Item | Value |\n|---|---|---|\n")
		for _, line := range res.Lines {
			value := strings.ReplaceAll(line.Value, "|", "\\|")
			fmt.Fprintf(w, "| %s | %s | `%s` |\n", mdStatus(line.Status), line.Key, value)
		}
		fmt.Fprintln(w)
	}

	fmt.Fprintf(w, "---\n\n*Generated by go-clustercheck v%s*\n", version)
}
